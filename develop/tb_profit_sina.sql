    diluted_eps DECIMAL(10,4) , -- '稀释每股收益',
    data_source VARCHAR(50) , -- '数据源',
    is_audited VARCHAR(20) , -- '是否审计',
    announcement_date VARCHAR(8) , -- '公告日期',
    currency VARCHAR(10) , -- '币种',
    report_type VARCHAR(50) , -- '类型',
    update_date TIMESTAMP,  -- '更新日期',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, -- '创建时间'
    update_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, -- '更新时间'
    is_deleted BOOLEAN DEFAULT FALSE -- '是否删除'
