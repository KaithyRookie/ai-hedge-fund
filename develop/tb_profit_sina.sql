    operating_profit DECIMAL(15,2) , -- '营业利润',
    non_operating_income DECIMAL(15,2) , -- '营业外收入',
    non_current_asset_disposal_gain DECIMAL(15,2) , -- '非流动资产处置利得',
    non_operating_expense DECIMAL(15,2) , -- '营业外支出',
    non_current_asset_disposal_loss DECIMAL(15,2) , -- '非流动资产处置损失',
    total_profit DECIMAL(15,2) , -- '利润总额',
    income_tax_expense DECIMAL(15,2) , -- '所得税费用',
